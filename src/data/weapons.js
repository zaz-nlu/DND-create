export function getWeaponById(id) {
  return weapons.find(weapon => weapon.id === id) ?? null
}

export function getWeaponPropertyById(id) {
  return weaponProperties.find(property => property.id === id) ?? null
}

export function getWeaponMasteryById(id) {
  return weaponMasteryProperties.find(property => property.id === id) ?? null
}

export function getWeaponsByCategory(category) {
  return weapons.filter(weapon => weapon.category === category)
}
