export const classes = reactive([
  ...builtinClasses,
  ...readImportedClasses(),
])

export function upsertRuntimeClass(classDef) {
  const index = classes.findIndex(item => item.id === classDef.id)

  if (index >= 0) {
    classes[index] = classDef
  } else {
    classes.push(classDef)
  }
}
