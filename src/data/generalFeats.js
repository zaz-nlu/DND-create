export function isGeneralFeatUnlockedByLevel(feat, level) {
  return level >= (feat.prerequisites?.minLevel ?? 1)
}

function hasAbilityScore(scores, requirement) {
  return Number(scores?.[requirement.id]) >= requirement.min
}

function formatAbilityRequirement(requirement) {
  return `${requirement.id} ${requirement.min}+`
}

export function getGeneralFeatAvailability(feat, context = {}) {
  const level = Number(context.level) || 1
  const scores = context.scores ?? {}
  const traits = context.traits ?? {}
  const prerequisites = feat.prerequisites ?? {}
  const reasons = []

  if (level < (prerequisites.minLevel ?? 1)) {
    reasons.push(`需要等级 ${prerequisites.minLevel}+`)
  }

  if (Array.isArray(prerequisites.abilities)) {
    prerequisites.abilities.forEach(requirement => {
      if (!hasAbilityScore(scores, requirement)) {
        reasons.push(`需要 ${formatAbilityRequirement(requirement)}`)
      }
    })
  }

  if (Array.isArray(prerequisites.anyAbility) &&
      !prerequisites.anyAbility.some(requirement => hasAbilityScore(scores, requirement))) {
    reasons.push(`需要 ${prerequisites.anyAbility.map(formatAbilityRequirement).join(' 或 ')}`)
  }

  if (prerequisites.trait && traits[prerequisites.trait] !== true) {
    reasons.push('需要对应职业训练或施法特性')
  }

  return {
    canSelect: reasons.length === 0,
    reasons,
  }
}

export function findGeneralFeatById(id) {
  return generalFeats.find(feat => feat.id === id) ?? null
}
